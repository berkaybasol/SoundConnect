    @Override
    @Transactional(readOnly = true, propagation = Propagation.REQUIRES_NEW, timeout = 5)
    public List<MusicianFeedCandidate> findCandidates(MusicianFeedCandidateRequest request) {
        boolean likes = request.supportedTypes().contains(MusicianFeedItemType.ACTIVITY_LIKE);
        boolean comments = request.supportedTypes().contains(MusicianFeedItemType.ACTIVITY_COMMENT);
        if (!likes && !comments) return List.of();

        EnumSet<ActivityTarget> renderers = supportedTargets(request.supportedTypes());
        if (renderers.isEmpty()) return List.of();
        ZonedDateTime now = request.readAt().atZone(EVENT_ZONE);
        var parameters = baseParameters(request, now)
                .addValue("includeLikes", likes).addValue("includeComments", comments)
                .addValue("includeMedia", renderers.contains(ActivityTarget.MEDIA))
                .addValue("includeTracks", request.supportedTypes().contains(MusicianFeedItemType.TRACK))
                .addValue("includeProfileMedia", request.supportedTypes().contains(MusicianFeedItemType.PROFILE_MEDIA))
                .addValue("includeEvents", renderers.contains(ActivityTarget.EVENT))
                .addValue("includeEventPosts", renderers.contains(ActivityTarget.EVENT_POST))
                .addValue("includeTablePosts", renderers.contains(ActivityTarget.TABLE_GROUP_POST))
                .addValue("includeOverthinkingPosts", renderers.contains(ActivityTarget.OVERTHINKING_PROFILE_SHARE))
                .addValue("targetTypes", renderers.stream().map(ActivityTarget::databaseType).toList())
                .addValue("visibleActorLimit", MAX_VISIBLE_ACTORS)
                .addValue("limit", request.limit());
        List<ActivityRow> rows = jdbc.query(ACTIVITY_SQL, parameters, this::activityRow);
        if (rows.isEmpty()) return List.of();

        Map<TargetKey, TargetProjection> targets = hydrateTargets(request, now, rows);
        Map<String, LikeGroup> likesByTarget = new LinkedHashMap<>();
        List<MusicianFeedCandidate> result = new ArrayList<>();
        for (ActivityRow row : rows) {
            TargetProjection projection = targets.get(new TargetKey(row.targetType(), row.targetId()));
            if (projection == null) continue;
            if ("COMMENT".equals(row.action())) {
                result.add(candidate(row.itemId(), MusicianFeedItemType.ACTIVITY_COMMENT, row.occurredAt(),
                        row.actor(), List.of(row.actor()), 0, projection,
                        MusicianFeedReasonCode.FOLLOWED_USER_COMMENTED, 900_000L));
            } else {
                likesByTarget.computeIfAbsent(row.itemId(), ignored -> new LikeGroup(row, projection)).add(row);
            }
        }
        likesByTarget.values().stream().map(LikeGroup::candidate).forEach(result::add);
        result.sort(Comparator.comparing(MusicianFeedCandidate::occurredAt).reversed()
                .thenComparing(MusicianFeedCandidate::itemId));
        return List.copyOf(result.stream().limit(request.limit()).toList());
    }

    private MapSqlParameterSource baseParameters(MusicianFeedCandidateRequest request, ZonedDateTime now) {
        return new MapSqlParameterSource().addValue("viewerId", request.viewerUserId())
                .addValue("feedSessionId", request.feedSessionId())
                .addValue("anchor", MusicianFeedJdbcSupport.timestamp(request.anchor()))
                .addValue("readAt", MusicianFeedJdbcSupport.timestamp(request.readAt()))
                .addValue("today", now.toLocalDate()).addValue("nowSeconds", now.toLocalTime().toSecondOfDay())
                .addValue("storageMidnight", MusicianFeedJdbcSupport.hibernateUtcStorageTime(LocalTime.MIDNIGHT));
    }

    private EnumSet<ActivityTarget> supportedTargets(Set<MusicianFeedItemType> types) {
        EnumSet<ActivityTarget> result = EnumSet.noneOf(ActivityTarget.class);
        if (types.contains(MusicianFeedItemType.TRACK) || types.contains(MusicianFeedItemType.PROFILE_MEDIA)) {
            result.add(ActivityTarget.MEDIA);
        }
        if (types.contains(MusicianFeedItemType.EVENT)) result.add(ActivityTarget.EVENT);
        if (types.contains(MusicianFeedItemType.EVENT_PROFILE_SHARE)) result.add(ActivityTarget.EVENT_POST);
        if (types.contains(MusicianFeedItemType.TABLEGROUP_PROFILE_SHARE)) result.add(ActivityTarget.TABLE_GROUP_POST);
        if (types.contains(MusicianFeedItemType.OVERTHINKING_PROFILE_SHARE)) {
            result.add(ActivityTarget.OVERTHINKING_PROFILE_SHARE);
        }
        return result;
    }

    private ActivityRow activityRow(ResultSet row, int index) throws SQLException {
        var actor = new MusicianFeedItemResponse.Author(
                MusicianFeedJdbcSupport.uuid(row, "actor_user_id"),
                MusicianFeedJdbcSupport.uuid(row, "actor_profile_id"), row.getString("actor_profile_type"),
                row.getString("actor_username"), row.getString("actor_display_name"),
                row.getString("actor_avatar_url"), true);
        return new ActivityRow(row.getString("item_id"), row.getString("action"),
                row.getString("target_type"), MusicianFeedJdbcSupport.uuid(row, "target_id"),
                MusicianFeedJdbcSupport.instant(row, "occurred_at"), actor, row.getLong("actor_count"));
    }

    private Map<TargetKey, TargetProjection> hydrateTargets(
            MusicianFeedCandidateRequest request,
            ZonedDateTime now,
            Collection<ActivityRow> rows
    ) {
        Map<String, LinkedHashSet<UUID>> ids = new LinkedHashMap<>();
        for (ActivityRow row : rows) ids.computeIfAbsent(row.targetType(), ignored -> new LinkedHashSet<>())
                .add(row.targetId());
        Map<TargetKey, TargetProjection> result = new LinkedHashMap<>();
        var base = baseParameters(request, now)
                .addValue("includeTracks", request.supportedTypes().contains(MusicianFeedItemType.TRACK))
                .addValue("includeProfileMedia", request.supportedTypes().contains(MusicianFeedItemType.PROFILE_MEDIA));
        query(ids, ActivityTarget.MEDIA, MEDIA_TARGET_SQL, base, this::mediaTarget, result);
        query(ids, ActivityTarget.EVENT, EVENT_TARGET_SQL, base, this::eventTarget, result);
        query(ids, ActivityTarget.EVENT_POST, EVENT_POST_TARGET_SQL, base, this::eventPostTarget, result);
        query(ids, ActivityTarget.TABLE_GROUP_POST, TABLE_TARGET_SQL, base, this::tableTarget, result);

        LinkedHashSet<UUID> overthinkingIds = ids.get(ActivityTarget.OVERTHINKING_PROFILE_SHARE.databaseType());
        if (overthinkingIds != null && !overthinkingIds.isEmpty()) {
            List<OverthinkingTargetRow> sourceRows = jdbc.query(OVERTHINKING_TARGET_SQL,
                    copy(base).addValue("targetIds", List.copyOf(overthinkingIds)), this::overthinkingTargetRow);
            Map<UUID, OverthinkingPostResponseDto> sources = MusicianFeedOverthinkingSources.resolve(
                    overthinkingPosts, request.viewerUserId(), sourceRows.stream()
                            .map(OverthinkingTargetRow::sourceId).toList());
            for (OverthinkingTargetRow row : sourceRows) {
                OverthinkingPostResponseDto source = sources.get(row.sourceId());
                if (source == null) continue;
                var payload = new MusicianFeedPayloads.ProfileShare(row.targetId(), row.note(),
                        row.publishedAt(), source);
                result.put(new TargetKey(ActivityTarget.OVERTHINKING_PROFILE_SHARE.databaseType(), row.targetId()),
                        new TargetProjection(MusicianFeedItemType.OVERTHINKING_PROFILE_SHARE, payload,
                                row.engagement()));
            }
        }
        return Map.copyOf(result);
    }

    private void query(
            Map<String, LinkedHashSet<UUID>> ids,
            ActivityTarget type,
            String sql,
            MapSqlParameterSource parameters,
            org.springframework.jdbc.core.RowMapper<TargetProjection> mapper,
            Map<TargetKey, TargetProjection> output
    ) {
        LinkedHashSet<UUID> targetIds = ids.get(type.databaseType());
        if (targetIds == null || targetIds.isEmpty()) return;
        for (TargetProjection value : jdbc.query(sql,
                copy(parameters).addValue("targetIds", List.copyOf(targetIds)), mapper)) {
            output.put(new TargetKey(type.databaseType(), value.engagement().targetId()), value);
        }
    }

    private MapSqlParameterSource copy(MapSqlParameterSource source) {
        MapSqlParameterSource result = new MapSqlParameterSource();
        for (String name : source.getParameterNames()) result.addValue(name, source.getValue(name));
        return result;
    }


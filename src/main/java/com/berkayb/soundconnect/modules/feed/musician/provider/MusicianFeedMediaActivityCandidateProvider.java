    private EventResponseDto event(ResultSet row, UUID eventId) throws SQLException {
        UUID musicianId = MusicianFeedJdbcSupport.uuid(row, "musician_profile_id");
        UUID bandId = MusicianFeedJdbcSupport.uuid(row, "band_id");
        String manualName = row.getString("manual_performer_name");
        PerformerType performerType = bandId != null ? PerformerType.BAND
                : musicianId != null ? PerformerType.MUSICIAN
                : manualName != null && !manualName.isBlank() ? PerformerType.MANUAL : null;
        String performerName = bandId != null ? row.getString("band_name")
                : musicianId != null ? firstText(row.getString("musician_stage_name"),
                row.getString("musician_username")) : firstText(manualName, "Belirtilmemiş");
        return new EventResponseDto(eventId, row.getString("title"), row.getString("poster_image"),
                performerName, musicianId, bandId, performerType, Set.of(),
                MusicianFeedJdbcSupport.uuid(row, "venue_id"), row.getString("venue_name"),
                row.getString("venue_city"), row.getString("venue_district"),
                row.getString("venue_neighborhood"), row.getObject("event_date", LocalDate.class),
                MusicianFeedJdbcSupport.normalizedTime(row, "normalized_start_seconds"),
                MusicianFeedJdbcSupport.normalizedTime(row, "normalized_end_seconds"),
                row.getString("description"), shareUrls.buildEventShareUrl(eventId),
                EventOrigin.valueOf(row.getString("event_origin")),
                EventVenueApprovalStatus.valueOf(row.getString("venue_approval_status")),
                row.getBoolean("venue_calendar_approved"));
    }

    private MusicianFeedCandidate candidate(
            String itemId,
            MusicianFeedItemType type,
            Instant occurredAt,
            MusicianFeedItemResponse.Author actor,
            List<MusicianFeedItemResponse.Author> actors,
            int secondaryActorCount,
            TargetProjection target,
            MusicianFeedReasonCode reasonCode,
            long score
    ) {
        String action = type == MusicianFeedItemType.ACTIVITY_COMMENT ? "COMMENT" : "LIKE";
        var payload = new MusicianFeedPayloads.Activity(action, actor,
                target.itemType(), target.payload());
        String targetType = target.engagement().targetType();
        MusicianFeedLane lane = "TABLE_GROUP_POST".equals(targetType)
                || "OVERTHINKING_PROFILE_SHARE".equals(targetType)
                ? MusicianFeedLane.MODULE_SHARE : MusicianFeedLane.FOLLOWING;
        return new MusicianFeedCandidate(itemId, type, 1, occurredAt,
                new MusicianFeedItemResponse.Reason(reasonCode, actors, secondaryActorCount), actor,
                new MusicianFeedItemResponse.Target(target.engagement().targetType(),
                        target.engagement().targetId()),
                target.engagement(), null, MusicianFeedJdbcSupport.standardFeedback(), payload,
                score, 0, lane, false);
    }

    private static String firstText(String... values) {
        return Arrays.stream(values).filter(value -> value != null && !value.isBlank()).findFirst().orElse(null);
    }

